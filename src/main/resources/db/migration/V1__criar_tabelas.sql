CREATE TABLE categoria (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(255) NOT NULL UNIQUE
);

CREATE TABLE subcategoria (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(255) NOT NULL,
    categoria_id BIGINT NOT NULL,
    CONSTRAINT fk_subcategoria_categoria
        FOREIGN KEY (categoria_id) REFERENCES categoria(id)
);

CREATE TABLE conta (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(255) NOT NULL,
    email VARCHAR(255) NOT NULL,
    senha VARCHAR(255) NOT NULL,
    telefone VARCHAR(255) NOT NULL
);

CREATE TABLE banner (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    titulo VARCHAR(255) NOT NULL,
    imagem VARCHAR(255) NOT NULL,
    ativo BOOLEAN NOT NULL
);

CREATE TABLE produto (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(255) NOT NULL,
    descricao VARCHAR(1000),
    preco DOUBLE NOT NULL,
    quantidade INTEGER NOT NULL,
    altura DOUBLE,
    largura DOUBLE,
    diametro DOUBLE,
    circunferencia DOUBLE,
    peso_aprox DOUBLE,
    imagem_principal VARCHAR(255) NOT NULL,
    ativo BOOLEAN NOT NULL,
    destaque BOOLEAN NOT NULL,
    categoria_id BIGINT NOT NULL,
    subcategoria_id BIGINT,
    CONSTRAINT fk_produto_categoria
        FOREIGN KEY (categoria_id) REFERENCES categoria(id),
    CONSTRAINT fk_produto_subcategoria
        FOREIGN KEY (subcategoria_id) REFERENCES subcategoria(id)
);

CREATE TABLE pedido (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    conta_id BIGINT NOT NULL,
    observacao_geral VARCHAR(1000),
    total DOUBLE NOT NULL,
    status VARCHAR(255) NOT NULL,
    data_pedido TIMESTAMP NOT NULL,
    cep VARCHAR(255) NOT NULL,
    logradouro VARCHAR(255) NOT NULL,
    numero VARCHAR(255) NOT NULL,
    bairro VARCHAR(255) NOT NULL,
    cidade VARCHAR(255) NOT NULL,
    estado VARCHAR(255) NOT NULL,
    CONSTRAINT fk_pedido_conta
        FOREIGN KEY (conta_id) REFERENCES conta(id)
);

CREATE TABLE pedido_item (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pedido_id BIGINT NOT NULL,
    produto_id BIGINT NOT NULL,
    quantidade INTEGER NOT NULL,
    valor_unitario DOUBLE NOT NULL,
    observacao_item VARCHAR(1000),
    CONSTRAINT fk_pedido_item_pedido
        FOREIGN KEY (pedido_id) REFERENCES pedido(id),
    CONSTRAINT fk_pedido_item_produto
        FOREIGN KEY (produto_id) REFERENCES produto(id)
);